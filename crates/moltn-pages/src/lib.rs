//! File-based routing for Inertia on axum: one page is one file in `pages/`,
//! the URL follows from its path, and the server logic is a Rust `#[page]` loader.
//!
//! | File | Route | Component |
//! |---|---|---|
//! | `index.vue` | `/` | `index` |
//! | `users/[id].vue` | `/users/{id}` | `users/[id]` |
//! | `users/[[tab]].vue` | `/users`, `/users/{tab}` | `users/[[tab]]` |
//! | `docs/[...slug].vue` | `/docs/{*slug}` | `docs/[...slug]` |
//! | `(admin)/stats.vue` | `/stats` | `(admin)/stats` |
//! | `_components/Card.vue` | *(ignored)* | — |
//!
//! Three pieces:
//! - `build.rs`: [`build::scan`] reads the folder and writes the page table;
//! - [`page`]: a loader, an ordinary axum handler returning `Result<Props, E>`;
//! - [`router`]: pairs pages with loaders, and checks everything at startup.
//!
//! ```ignore
//! // build.rs : moltn_pages::build::scan("web/src/pages").unwrap();
//!
//! // main.rs
//! #[derive(serde::Serialize, ts_rs::TS)]
//! struct UserProps { user: User }
//!
//! #[moltn_pages::page("users/[id]")]
//! async fn user_show(Path(id): Path<u32>, State(app): State<AppState>) -> Result<UserProps, AppError> {
//!     Ok(UserProps { user: app.users.find(id).await? })
//! }
//!
//! let app = moltn_pages::router::<AppState>(moltn_pages::pages!())?
//!     .route("/users", post(create_user))   // mutations: regular axum routes
//!     .layer(veer::InertiaLayer::new(config))
//!     .with_state(state);
//! ```

pub mod build;
pub mod config;
mod ts_render;

#[cfg(feature = "runtime")]
mod runtime;
#[cfg(feature = "runtime")]
mod typescript;

#[cfg(feature = "runtime")]
pub use runtime::*;
#[cfg(feature = "runtime")]
pub use typescript::{sync_typescript, typescript};

/// A page of the table generated by [`build::scan`].
#[derive(Debug, Clone, Copy)]
pub struct PageFile {
    /// File relative to the pages folder (`users/[id].vue`).
    pub file: &'static str,
    /// Inertia component name (`users/[id]`).
    pub component: &'static str,
    /// axum routes.
    pub routes: &'static [&'static str],
    /// Names of the dynamic parameters.
    pub params: &'static [&'static str],
}

/// The application's page table and the location of the generated TypeScript module.
#[derive(Debug, Clone, Copy)]
pub struct PageTable {
    /// Pages, sorted by file.
    pub pages: &'static [PageFile],
    /// `moltn.ts` to keep up to date (absolute path), `None` to write nothing.
    pub typescript: Option<&'static str>,
}

/// Page table written by [`build::scan`] into the application's `OUT_DIR`.
///
/// ```ignore
/// let table: &'static moltn_pages::PageTable = moltn_pages::pages!();
/// ```
#[macro_export]
macro_rules! pages {
    () => {
        include!(concat!(env!("OUT_DIR"), "/moltn_pages.rs"))
    };
}
