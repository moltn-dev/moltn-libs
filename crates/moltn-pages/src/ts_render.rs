//! Rendu du module `moltn.ts`, sans dépendance au runtime. Partagé par l'application (qui
//! connaît les types des props) et par `moltn dev` (qui met à jour pages et routes dès qu'un
//! fichier de `pages/` est créé, déplacé ou supprimé, sans attendre la compilation).

use std::collections::BTreeMap;
use std::fmt::Write as _;

const HEADER: &str = "// Generated by moltn. Do not edit.\n\
     // Props types come from Rust structs (ts-rs). Updated when the application starts\n\
     // in debug, or by `moltn gen`; checked in CI by `moltn gen --check`.\n\n";
const PAGES_START: &str = "/** Props of each page, by component: `defineProps<Pages['users/[id]']>()`. */\nexport interface Pages {\n";
const PAGES_END: &str = "}\n\n";
const SHARED_DOC: &str = "/** Props shared by every page (`moltn_pages::shared_props!`). */\n";
const ROUTES_DOC: &str = "/** URL parameters of each page, by component. */\n";

/// Une page vue par le rendu des routes.
pub(crate) struct RoutePage<'a> {
    pub component: &'a str,
    pub routes: Vec<&'a str>,
    pub params: Vec<&'a str>,
}

/// Ce qui demande le code Rust compilé : déclarations, types des props, props partagées.
pub(crate) struct Typed {
    /// Déclarations `export type …;`, déjà mises en forme.
    pub decls: String,
    /// Type des props par composant ; une page absente reçoit `{}`.
    pub props: BTreeMap<String, String>,
    /// Section des props partagées (voir [`shared_section`]).
    pub shared: String,
}

impl Typed {
    /// Aucun type connu (fichier absent ou illisible).
    pub(crate) fn empty() -> Self {
        Self {
            decls: String::new(),
            props: BTreeMap::new(),
            shared: shared_section(&[]),
        }
    }

    /// Relit les parties typées d'un `moltn.ts` produit par [`render`].
    pub(crate) fn parse(existing: &str) -> Option<Self> {
        let rest = existing.strip_prefix(HEADER)?;
        let (decls, rest) = rest.split_once(PAGES_START)?;
        let (entries, rest) = rest.split_once(PAGES_END)?;
        let props = entries
            .lines()
            .filter_map(|line| {
                let (component, ty) = line.strip_prefix("  '")?.split_once("': ")?;
                Some((component.to_string(), ty.to_string()))
            })
            .collect();
        let (shared, _routes) = rest.split_once(ROUTES_DOC)?;
        Some(Self {
            decls: decls.to_string(),
            props,
            shared: shared.strip_suffix('\n')?.to_string(),
        })
    }
}

/// Section des props partagées, à partir des noms de types enregistrés.
pub(crate) fn shared_section(shared: &[String]) -> String {
    let mut out = String::from(SHARED_DOC);
    if shared.is_empty() {
        out.push_str("export type SharedProps = {}\n");
    } else {
        let _ = writeln!(out, "export type SharedProps = {}", shared.join(" & "));
        out.push_str(
            "\n// Inertia's global typing: `usePage().props` knows the shared props.\n\
             declare module '@inertiajs/core' {\n  interface InertiaConfig {\n    sharedPageProps: SharedProps\n  }\n}\n",
        );
    }
    out
}

/// Contenu complet de `moltn.ts`.
pub(crate) fn render(typed: &Typed, pages: &mut [RoutePage<'_>]) -> String {
    pages.sort_by_key(|p| p.component);
    let mut out = String::from(HEADER);
    out.push_str(&typed.decls);
    out.push_str(PAGES_START);
    for page in pages.iter() {
        let ty = typed.props.get(page.component).map_or("{}", String::as_str);
        let _ = writeln!(out, "  '{}': {ty}", page.component);
    }
    out.push_str(PAGES_END);
    out.push_str(&typed.shared);
    out.push('\n');
    out.push_str(&routes(pages));
    out
}

/// `RouteParams` et `route()`.
fn routes(pages: &[RoutePage<'_>]) -> String {
    let mut params = String::new();
    let mut templates = String::new();
    for page in pages {
        let mut template = page.routes.last().copied().unwrap_or("/").to_string();
        let optional = page.routes.len() == 2;
        let fields: Vec<String> = page
            .params
            .iter()
            .enumerate()
            .map(|(i, name)| {
                if template.contains(&format!("{{*{name}}}")) {
                    format!("{name}: string[]")
                } else if optional && i == page.params.len() - 1 {
                    format!("{name}?: string | number")
                } else {
                    format!("{name}: string | number")
                }
            })
            .collect();
        if optional && let Some(name) = page.params.last() {
            template = template.replace(&format!("{{{name}}}"), &format!("{{{name}?}}"));
        }
        let fields = if fields.is_empty() {
            "{}".to_string()
        } else {
            format!("{{ {} }}", fields.join("; "))
        };
        let _ = writeln!(params, "  '{}': {fields}", page.component);
        let _ = writeln!(templates, "  '{}': '{template}',", page.component);
    }
    format!(
        r#"{ROUTES_DOC}export interface RouteParams {{
{params}}}

const templates: Record<keyof RouteParams, string> = {{
{templates}}}

type Query = Record<string, string | number>
type Args<K extends keyof RouteParams> = {{}} extends RouteParams[K]
  ? [params?: RouteParams[K], query?: Query]
  : [params: RouteParams[K], query?: Query]

/** URL of a page: `route('users/[id]', {{ id: 42 }})` → `/users/42`. */
export function route<K extends keyof RouteParams>(name: K, ...[params, query]: Args<K>): string {{
  const values = (params ?? {{}}) as Record<string, string | number | string[] | undefined>
  let path = templates[name].replace(/\/\{{(\*?)(\w+)(\??)\}}/g, (_, star: string, key: string, optional: string) => {{
    const value = values[key]
    if (value === undefined || (Array.isArray(value) && value.length === 0)) {{
      if (optional) return ''
      throw new Error(`route('${{name}}'): missing parameter "${{key}}"`)
    }}
    const parts = star ? (value as string[]) : [String(value)]
    return '/' + parts.map(encodeURIComponent).join('/')
  }})
  if (path === '') path = '/'
  const search = new URLSearchParams(Object.entries(query ?? {{}}).map(([k, v]) => [k, String(v)])).toString()
  return search ? `${{path}}?${{search}}` : path
}}
"#
    )
}
